#!/usr/bin/env bash
# LACUNA-AMR — one-command deploy from a clean checkout (Phase 1, v0.5.0).
#
#   git clone <repo> lacuna-amr && cd lacuna-amr && ./deploy/deploy.sh
#
# What it does:
#   0. sanity-checks docker + compose + env
#   1. creates .env from .env.example on first run (generating secrets)
#   2. builds and starts db + app + caddy + backup (docker compose)
#   3. pushes the Prisma schema to Postgres (idempotent)
#   4. waits for /api/health to report ok
#   5. prints the URLs and next steps
#
# Rollback:  docker compose -f deploy/docker-compose.yml down
#            (data persists in the db-data volume; restore via restore-drill.sh)
set -euo pipefail

cd "$(dirname "$0")/.."   # repo root
COMPOSE="docker compose -f deploy/docker-compose.yml"

say() { echo -e "\033[0;32m[deploy]\033[0m $*"; }
die() { echo -e "\033[0;31m[deploy]\033[0m $*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || die "docker is required (https://docs.docker.com/get-docker/)"
$COMPOSE version >/dev/null 2>&1 || die "docker compose v2 is required"

# 1. environment ---------------------------------------------------------------
if [ ! -f .env ]; then
  say "no .env found — creating one from .env.example with generated secrets"
  SECRET_DB="$(docker run --rm alpine/openssl rand -hex 24)"
  cp .env.example .env
  sed -i.bak "s|^POSTGRES_PASSWORD=.*|POSTGRES_PASSWORD=${SECRET_DB}|" .env && rm -f .env.bak
  cat >> .env <<EOF

# --- generated by deploy.sh $(date -u +%FT%TZ) ---
EOF
  say ".env created — edit LACUNA_DOMAIN / LACUNA_ACME_EMAIL before exposing publicly"
fi

# shellcheck disable=SC1091
set -a; . ./.env; set +a
[ -n "${POSTGRES_PASSWORD:-}" ] || die "POSTGRES_PASSWORD must be set in .env"
[ -n "${LACUNA_DOMAIN:-}" ] || die "LACUNA_DOMAIN must be set in .env"

# 2. build + start --------------------------------------------------------------
say "building and starting the stack (db, app, caddy, backup)…"
$COMPOSE up -d --build

# 3. database schema -------------------------------------------------------------
say "pushing the Prisma schema to Postgres (idempotent)…"
$COMPOSE run --rm --no-deps app bunx prisma db push \
  --schema deploy/postgres/schema.postgres.prisma --skip-generate --accept-data-loss

# 4. health gate -----------------------------------------------------------------
say "waiting for /api/health…"
for i in $(seq 1 60); do
  STATUS=$(docker compose -f deploy/docker-compose.yml exec -T app \
    bun -e "fetch('http://127.0.0.1:3000/api/health').then(r=>r.json()).then(j=>console.log(j.status)).catch(()=>console.log('down'))" 2>/dev/null || echo down)
  [ "$STATUS" = "ok" ] && break
  sleep 2
done
[ "$STATUS" = "ok" ] || die "app did not become healthy — inspect: $COMPOSE logs app"
say "app is healthy."

# 5. summary ---------------------------------------------------------------------
cat <<EOF

LACUNA-AMR v0.5.0 is up.

  console    : https://${LACUNA_DOMAIN}
  health     : https://${LACUNA_DOMAIN}/api/health
  metrics    : https://${LACUNA_DOMAIN}/api/metrics        (basic auth, see deploy/Caddyfile)
  backups    : deploy/postgres/backups/ (nightly 02:17 UTC + weekly restore drill)

Next steps:
  * create the first account (it becomes an organization owner)
  * set STRIPE_SECRET_KEY in .env to switch billing from sandbox to Stripe
  * run a restore drill any time: deploy/postgres/restore-drill.sh
EOF
